def _decode_raw_event(raw):
    if isinstance(raw, dict):
        return raw
    if not isinstance(raw, str):
        return {}
    try:
        decoded = json.loads(base64.b64decode(raw, validate=True).decode('utf-8'))
    except _JSON_ERRORS:
        return {}
    return decoded if isinstance(decoded, dict) else {}


